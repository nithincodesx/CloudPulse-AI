-- 1. Servers table
CREATE TABLE IF NOT EXISTS servers (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  server_name    TEXT NOT NULL,
  ip_address     TEXT,
  status         TEXT NOT NULL DEFAULT 'active'
                   CHECK (status IN ('active', 'warning', 'critical', 'idle')),
  specifications JSONB DEFAULT '{}'::jsonb,
  owner_id       UUID REFERENCES auth.users(id),           -- who owns this node
  ingestion_token TEXT NOT NULL DEFAULT encode(gen_random_bytes(32), 'hex')
                   UNIQUE,                                 -- 256-bit bearer token for the agent
  cost_tag       TEXT,                                     -- AWS resource-tag value this node maps to
  created_at     TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Server metrics (time-series logs)
-- NOTE: cost is NOT stored per metric anymore — real spend lives in daily_costs
-- (populated from AWS Cost Explorer). estimated_cost_per_hour is kept nullable
-- only for legacy rows written before this change.
CREATE TABLE IF NOT EXISTS server_metrics (
  id                      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  server_id               UUID NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
  cpu_usage               FLOAT NOT NULL,
  ram_usage               FLOAT NOT NULL,
  network_traffic         FLOAT NOT NULL,
  estimated_cost_per_hour FLOAT,
  recorded_at             TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_metrics_server_time
  ON server_metrics (server_id, recorded_at DESC);

-- 2b. Daily costs (real spend, per server, from AWS Cost Explorer)
CREATE TABLE IF NOT EXISTS daily_costs (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  server_id   UUID NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
  cost_date   DATE NOT NULL,
  amount      NUMERIC(12,4) NOT NULL,
  currency    TEXT NOT NULL DEFAULT 'USD',
  source      TEXT NOT NULL DEFAULT 'aws_cost_explorer',
  created_at  TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  UNIQUE (server_id, cost_date)
);

CREATE INDEX IF NOT EXISTS idx_daily_costs_server_date
  ON daily_costs (server_id, cost_date DESC);

-- 3. System alerts
CREATE TABLE IF NOT EXISTS system_alerts (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  server_id  UUID NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
  alert_type TEXT NOT NULL CHECK (alert_type IN ('HIGH_CPU', 'IDLE_RESOURCE', 'BUDGET_SPIKE', 'NETWORK_ANOMALY')),
  message    TEXT NOT NULL,
  resolved   BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_alerts_unresolved
  ON system_alerts (resolved, created_at DESC);

-- 4. Weekly AI insights (deployment-wide plain-English summaries)
-- Generated by the backend's scheduled weekly job (Groq/Gemini free tier) from
-- REAL alerts + cost deltas + utilization. The LLM only summarizes real numbers;
-- anomaly detection is statistical (z-scores), NOT ML. UNIQUE(period_start,
-- period_end) makes scheduled retries idempotent.
CREATE TABLE IF NOT EXISTS weekly_insights (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  summary      TEXT NOT NULL,
  period_start DATE NOT NULL,
  period_end   DATE NOT NULL,
  provider     TEXT,
  model        TEXT,
  meta         JSONB NOT NULL DEFAULT '{}'::jsonb, -- server_count, alert_count, total_cost, generation_ms
  generated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  UNIQUE (period_start, period_end)
);

-- 5. Statistical anomaly-detection functions (PostgREST RPCs)
-- SECURITY INVOKER so RLS applies: anon/authenticated callers only see metrics
-- on servers they own; the backend's service-role key bypasses RLS. STABLE (uses
-- now()). Auto-exposed via PostgREST /rpc — GRANTs below are belt-and-suspenders.

-- Per-metric rolling baseline: 7-day mean/stddev per server (drives z-scores).
CREATE OR REPLACE FUNCTION public.metrics_baseline(p_server_id UUID, p_days INT)
RETURNS TABLE(
  cpu_mean float8, cpu_std float8,
  ram_mean float8, ram_std float8,
  net_mean float8, net_std float8,
  sample_count bigint
)
LANGUAGE sql STABLE SECURITY INVOKER
AS $$
  SELECT avg(cpu_usage)::float8,       stddev_pop(cpu_usage)::float8,
         avg(ram_usage)::float8,       stddev_pop(ram_usage)::float8,
         avg(network_traffic)::float8, stddev_pop(network_traffic)::float8,
         count(*)::bigint
  FROM public.server_metrics
  WHERE server_id = p_server_id
    AND recorded_at >= now() - make_interval(days => p_days);
$$;

-- Utilization snapshot for the weekly summary: total samples vs idle samples
-- (cpu < floor AND ram < floor) plus average utilization over the window.
CREATE OR REPLACE FUNCTION public.metrics_utilization(
  p_server_id UUID, p_days INT, p_cpu_floor float8, p_ram_floor float8
)
RETURNS TABLE(
  total_samples bigint, idle_samples bigint, avg_cpu float8, avg_ram float8
)
LANGUAGE sql STABLE SECURITY INVOKER
AS $$
  SELECT count(*)::bigint,
         count(*) FILTER (WHERE cpu_usage < p_cpu_floor AND ram_usage < p_ram_floor)::bigint,
         avg(cpu_usage)::float8,
         avg(ram_usage)::float8
  FROM public.server_metrics
  WHERE server_id = p_server_id
    AND recorded_at >= now() - make_interval(days => p_days);
$$;

